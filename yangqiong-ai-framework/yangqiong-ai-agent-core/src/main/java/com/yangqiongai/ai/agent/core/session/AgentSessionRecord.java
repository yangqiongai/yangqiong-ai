package com.yangqiongai.ai.agent.core.session;


import com.yangqiongai.ai.common.entity.ScopeEntity;

/**
 * Agent会话记录
 * @author yangqiong
 */
public class AgentSessionRecord extends ScopeEntity {

    private String sessionId;

    private String userId;

    private String agentCode;

    private String sessionType;

    private String sessionTitle;

    private Integer sessionStatus;

    private Integer summaryRound;

    /**
     * 会话摘要文本
     */
    private String summaryText;

    public String getSessionId() {
        return sessionId;
    }

    public void setSessionId(String sessionId) {
        this.sessionId = sessionId;
    }

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public String getAgentCode() {
        return agentCode;
    }

    public void setAgentCode(String agentCode) {
        this.agentCode = agentCode;
    }

    public String getSessionType() {
        return sessionType;
    }

    public void setSessionType(String sessionType) {
        this.sessionType = sessionType;
    }

    public String getSessionTitle() {
        return sessionTitle;
    }

    public void setSessionTitle(String sessionTitle) {
        this.sessionTitle = sessionTitle;
    }

    public Integer getSessionStatus() {
        return sessionStatus;
    }

    public void setSessionStatus(Integer sessionStatus) {
        this.sessionStatus = sessionStatus;
    }

    public Integer getSummaryRound() {
        return summaryRound;
    }

    public void setSummaryRound(Integer summaryRound) {
        this.summaryRound = summaryRound;
    }

    public String getSummaryText() {
        return summaryText;
    }

    public void setSummaryText(String summaryText) {
        this.summaryText = summaryText;
    }

}
